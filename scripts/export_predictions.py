"""Convert saved DA relative predictions and optionally apply returned residual refinement."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--method", choices=("da_v2", "simple_cnn", "multiscale_b", "gated_c0", "highlight_c1"), required=True)
    parser.add_argument("--split", choices=("dev", "test"), default="test")
    parser.add_argument("--data-root", type=Path, default=ROOT / "data")
    parser.add_argument("--relative-root", type=Path, default=ROOT / "outputs/intermediate/da_v2_relative")
    parser.add_argument("--output-root", type=Path, default=ROOT / "outputs")
    parser.add_argument("--calibration", type=Path, default=ROOT / "configs/inverse_calibration_clean.json")
    parser.add_argument("--checkpoint", type=Path, help="Required for refinement; filename is not used to infer a seed")
    parser.add_argument("--device", choices=("cpu", "cuda"), default="cpu")
    parser.add_argument("--strict-fp32", action="store_true", help="Disable TF32 for the one-frame-verified refinement precision settings")
    parser.add_argument("--max-frames", type=int, help="Small verification subset; use a separate output root")
    args = parser.parse_args()
    import torch
    # The original Notebook retained these settings from its training setup.
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True
    if args.strict_fp32:
        torch.backends.cudnn.allow_tf32 = False
        torch.backends.cuda.matmul.allow_tf32 = False
        torch.set_float32_matmul_precision("highest")
    from c3vd_eval.protocol import digest
    from c3vd_eval.runner import runtime_record, write_json
    from c3vd_models.artifacts import load_calibration, load_checkpoint, save_prediction
    from c3vd_models.data import load_dataset, RefinementDataset

    if args.method != "da_v2" and args.checkpoint is None:
        parser.error("--checkpoint is required for a refinement model")
    sequence = "trans_t1_a" if args.split == "dev" else "trans_t2_b"
    prediction_dir = args.output_root / "predictions" / args.method
    output = prediction_dir / sequence
    if output.exists() or (prediction_dir / "generation.json").exists():
        raise FileExistsError(f"Refusing to overwrite predictions: {prediction_dir}")
    a, b = load_calibration(args.calibration)
    metadata = json.loads((ROOT / "configs" / f"{args.method}.json").read_text())
    metadata["calibration"].update({"a": a, "b": b})
    metadata["weights_sha256"] = {"refinement_checkpoint": digest(args.checkpoint)} if args.checkpoint else {}
    metadata["prediction_origin"] = "generated by integrated export_predictions.py; see generation hashes"
    metadata["seed"] = None
    dataset = RefinementDataset(load_dataset(args.data_root, args.split), args.relative_root / sequence, a, b)
    count = len(dataset) if args.max_frames is None else args.max_frames
    if not 1 <= count <= len(dataset):
        raise ValueError("max-frames is outside the split")
    model = None if args.method == "da_v2" else load_checkpoint(args.method, args.checkpoint, args.device)
    if args.method == "highlight_c1":
        from c3vd_models.highlight import detect_highlight
    sample_ids, hashes = [], {}
    for index in range(count):
        sample = dataset[index]
        with torch.inference_mode():
            if model is None:
                result = sample["pred"]
            else:
                rgb = sample["rgb"][None].to(args.device)
                depth = sample["pred"][None].to(args.device)
                high = detect_highlight(sample["rgb"])[None].to(args.device) if args.method == "highlight_c1" else torch.zeros_like(depth)
                result = model(rgb, depth, high)[0]
        path = prediction_dir / (sample["sample_id"] + ".npy")
        save_prediction(path, result[0].detach().cpu().numpy() * 100)
        sample_ids.append(sample["sample_id"])
        hashes[sample["sample_id"]] = digest(path)
    write_json(prediction_dir / "generation.json", {
        **metadata,
        "method": args.method, "split": args.split, "frames": count, "sample_ids": sample_ids,
        "calibration_sha256": digest(args.calibration),
        "checkpoint_sha256": None if model is None else digest(args.checkpoint),
        "relative_prediction_sha256": {
            sid: digest(args.relative_root / (sid + ".npy")) for sid in sample_ids
        },
        "prediction_sha256": hashes, "device": args.device,
        "strict_fp32_requested": args.strict_fp32, "runtime": runtime_record(),
        "clipping": False, "note": "Raw model output; strict validity is checked separately by evaluation",
    })
    print(f"Exported {count} millimeter predictions to {output}")


if __name__ == "__main__":
    main()
